export interface BackfillCard { id: number; front: string; back: string; translation: string | null }

/**
 * Characters that never appear in a genuine meaning but are common in
 * injected payloads (SQL, template, shell, markup, URLs). Cards containing them
 * are left untouched so test/junk data is not dressed up as vocabulary.
 */
const SUSPICIOUS = /[<>{}$|\\;=@#`%]|--|\/\/|\b(?:select|union|sleep|waitfor|passwd|system\.ini|web-inf|http|www\.|owasp|cookie|zap)\b/i;

function cleanWord(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, ' ');
}

/**
 * Finds the headword a card is teaching. Handles the three card shapes in the
 * data: word → meaning, meaning → "word /ipa/" (reversed), and pronunciation
 * prompts ending with the word in capitals.
 */
export function resolveHeadword(card: BackfillCard): string | null {
  const front = card.front.trim();
  const back = card.back.trim();
  if (SUSPICIOUS.test(front) || SUSPICIOUS.test(back)) return null;

  const direct = cleanWord(front);
  if (CURATED_EXAMPLES[direct]) return direct;

  const reversed = /^([a-z][a-z -]*?)\s*\/[^/]+\/$/i.exec(back);
  if (reversed && CURATED_EXAMPLES[cleanWord(reversed[1]!)]) return cleanWord(reversed[1]!);

  const lastLine = front.split(/\n/).map(line => line.trim()).filter(Boolean).pop() ?? '';
  if (/^[A-Z][A-Z]+(?:\s+(?:and|AND)\s+[A-Z]+)*$/.test(lastLine)) {
    const words = lastLine.split(/\s+and\s+/i).map(cleanWord);
    const known = words.filter(word => CURATED_EXAMPLES[word]);
    if (known.length) return known.join('+');
  }
  return null;
}

/** Builds the stored example text for a resolved headword (one or more words). */
export function exampleFor(headword: string): string | null {
  const parts = headword.split('+').map(word => CURATED_EXAMPLES[word]).filter(Boolean) as Array<{ en: string; vi: string }>;
  if (!parts.length) return null;
  return parts.map(part => `${part.en}\n${part.vi}`).join('\n\n');
}
